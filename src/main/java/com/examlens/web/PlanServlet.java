package com.examlens.web;

import com.examlens.ai.AiOutcome;
import com.examlens.ai.dto.PlanDtos;
import com.examlens.model.Exam;
import com.examlens.service.StudyPlanService;
import com.examlens.util.Web;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;

/** P06/P07/P08/P17/P18 — the AI-generated, AI-replanned study plan and its history. */
@WebServlet(name = "plan", urlPatterns = {"/plan", "/plan/*"})
public class PlanServlet extends ServletSupport {

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse res) throws ServletException, IOException {
        String path = path(req);
        Exam exam = resolveExam(req, res);
        if (exam == null) {
            return;
        }
        long userId = userId(req);
        req.setAttribute("exam", exam);
        switch (path) {
            case "/plan" -> {
                StudyPlanService.PlanView view = ctx().plan().loadPlan(userId, exam.getId()).orElse(null);
                req.setAttribute("planView", view);
                req.setAttribute("explanation", view == null ? null : view.explanation().orElse(null));
                req.setAttribute("upcomingTasks", ctx().plan().upcoming(userId, exam.getId(), 6));
                int[] stats = ctx().plan().taskStats(userId, exam.getId());
                req.setAttribute("taskTotal", stats[0]);
                req.setAttribute("taskDone", stats[1]);
                render(req, res, "plan/index");
            }
            case "/plan/tasks" -> {
                StudyPlanService.PlanView view = ctx().plan().loadPlan(userId, exam.getId()).orElse(null);
                req.setAttribute("planView", view);
                render(req, res, "plan/tasks");
            }
            case "/plan/history" -> {
                req.setAttribute("versions", ctx().plan().versions(userId, exam.getId()));
                render(req, res, "plan/history");
            }
            case "/plan/feasibility" -> feasibility(req, res, exam.getId());
            default -> {
                res.setStatus(HttpServletResponse.SC_NOT_FOUND);
                render(req, res, "error/404");
            }
        }
    }

    @Override
    protected void doPost(HttpServletRequest req, HttpServletResponse res) throws IOException, ServletException {
        String path = path(req);
        long examId = Web.longParam(req, "examId", 0);
        String back = "/plan?examId=" + examId;
        switch (path) {
            case "/plan/feasibility" -> feasibility(req, res, examId);
            case "/plan/generate" -> action(req, res, back, () -> {
                ctx().plan().generate(userId(req), examId);
                Web.success(req, "Your study plan has been generated by the AI and saved as a new version.");
                return back;
            });
            case "/plan/replan" -> action(req, res, back, () -> {
                ctx().plan().replan(userId(req), examId);
                Web.success(req, "Plan revised around your latest progress and availability.");
                return back;
            });
            case "/plan/last-minute" -> action(req, res, back, () -> {
                ctx().plan().lastMinute(userId(req), examId);
                Web.success(req, "A last-minute revision plan was generated for your remaining time.");
                return back;
            });
            case "/plan/task/status" -> action(req, res, "/plan/tasks?examId=" + examId, () -> {
                ctx().plan().updateTaskStatus(userId(req), Web.longParam(req, "taskId", 0), Web.param(req, "status"));
                Web.success(req, "Task status updated.");
                return "/plan/tasks?examId=" + examId;
            });
            default -> redirect(req, res, back);
        }
    }

    private void feasibility(HttpServletRequest req, HttpServletResponse res, long examId)
            throws ServletException, IOException {
        try {
            AiOutcome<PlanDtos.FeasibilityResult> outcome = ctx().plan().assessFeasibility(userId(req), examId);
            req.setAttribute("exam", ctx().exams().require(userId(req), examId));
            req.setAttribute("feasibility", com.examlens.util.Json.toMap(outcome.getData()));
            req.setAttribute("simulated", outcome.isSimulated());
            render(req, res, "plan/feasibility");
        } catch (com.examlens.service.ServiceException e) {
            Web.error(req, e.getUserMessage());
            redirect(req, res, "/plan?examId=" + examId);
        } catch (com.examlens.ai.AiException e) {
            Web.error(req, aiMessage(e));
            redirect(req, res, "/plan?examId=" + examId);
        }
    }

    private String path(HttpServletRequest req) {
        String uri = req.getRequestURI().substring(req.getContextPath().length());
        return uri.endsWith("/") && uri.length() > 1 ? uri.substring(0, uri.length() - 1) : uri;
    }
}
